import Foundation

/// High-fidelity client implementation used for previews, tests, and standalone demo exploration.
public struct MockEngineClient: EngineClientProtocol {
    public init() {}

    public func checkHealth() async throws -> EngineHealth {
        return EngineHealth(
            isAlive: true,
            version: "1.0.0-mock",
            xcodeAvailable: true,
            activeProject: "DesignPilotDemo.xcodeproj"
        )
    }

    public func validateAccess(url: FigmaURL, token: String?) async throws -> Bool {
        try await Task.sleep(nanoseconds: 300_000_000)
        if url.fileKey.contains("invalid") || url.fileKey.count < 5 {
            throw DesignPilotError.figmaAccessDenied(reason: "Resource not found or invalid file key.")
        }
        return true
    }

    public func generate(
        request: GenerationRequest,
        onProgress: @Sendable @escaping (PipelineStage, Double, String) -> Void
    ) async throws -> GenerationResult {
        // Step 1: Validating URL & Access
        onProgress(.validatingURL, 0.15, "Verifying Figma file permissions...")
        try await Task.sleep(nanoseconds: 400_000_000)

        // Step 2: Retrieving Figma Nodes & Tokens
        onProgress(.fetchingDesign, 0.35, "Retrieved 24 AutoLayout frames, 8 components, and 12 styles")
        try await Task.sleep(nanoseconds: 500_000_000)

        // Step 3: Inspecting Target Project
        onProgress(.inspectingProject, 0.55, "Detected SwiftUI 6, iOS 16.0+, SF Pro typography conventions")
        try await Task.sleep(nanoseconds: 400_000_000)

        // Step 4: Synthesizing Code
        onProgress(.synthesizingCode, 0.75, "Generating adaptive SwiftUI hierarchy with dynamic type...")
        try await Task.sleep(nanoseconds: 600_000_000)

        // Step 5: Visual Validation
        onProgress(.visualValidation, 0.90, "Simulating layout on iPhone 16 Pro & iPad Air... (98.4% match)")
        try await Task.sleep(nanoseconds: 500_000_000)

        let screenTitle = request.figmaURL.documentTitle ?? "DashboardScreen"
        let sanitizedName = screenTitle
            .replacingOccurrences(of: "-", with: " ")
            .capitalized
            .replacingOccurrences(of: " ", with: "")

        let generatedSwiftUI = """
        //
        //  \(sanitizedName)View.swift
        //  Generated by DesignPilot SDK v1.0
        //  Figma Node: \(request.figmaURL.nodeId ?? "0:1")
        //

        import SwiftUI

        public struct \(sanitizedName)View: View {
            @Environment(\\.colorScheme) private var colorScheme
            @State private var isSelected: Bool = false

            public init() {}

            public var body: some View {
                ScrollView(.vertical, showsIndicators: false) {
                    VStack(alignment: .leading, spacing: 20) {
                        headerSection
                        metricCardsSection
                        actionBannerSection
                    }
                    .padding(.horizontal, 16)
                    .padding(.top, 12)
                }
                .background(Color("BackgroundColor", bundle: .main))
                .navigationTitle("\(sanitizedName)")
                .navigationBarTitleDisplayMode(.inline)
            }

            private var headerSection: some View {
                VStack(alignment: .leading, spacing: 6) {
                    Text("Welcome Back")
                        .font(.subheadline)
                        .foregroundStyle(.secondary)
                    Text("DesignPilot Studio")
                        .font(.system(size: 28, weight: .bold, design: .rounded))
                        .foregroundStyle(.primary)
                }
                .accessibilityElement(children: .combine)
            }

            private var metricCardsSection: some View {
                HStack(spacing: 14) {
                    MetricCardView(
                        title: "Active Tasks",
                        value: "142",
                        trend: "+12.4%",
                        accentColor: Color.blue
                    )
                    MetricCardView(
                        title: "Conversion",
                        value: "94.8%",
                        trend: "+3.1%",
                        accentColor: Color.green
                    )
                }
            }

            private var actionBannerSection: some View {
                Button(action: { isSelected.toggle() }) {
                    HStack {
                        VStack(alignment: .leading, spacing: 4) {
                            Text("Upgrade Pro Plan")
                                .font(.headline)
                                .foregroundColor(.white)
                            Text("Unlock unlimited AI code generation")
                                .font(.caption)
                                .foregroundColor(.white.opacity(0.8))
                        }
                        Spacer()
                        Image(systemName: "arrow.right.circle.fill")
                            .font(.title2)
                            .foregroundColor(.white)
                    }
                    .padding(16)
                    .background(
                        LinearGradient(
                            colors: [Color.blue, Color.purple],
                            startPoint: .topLeading,
                            endPoint: .bottomTrailing
                        )
                    )
                    .clipShape(RoundedRectangle(cornerRadius: 16, style: .continuous))
                    .shadow(color: Color.blue.opacity(0.3), radius: 8, x: 0, y: 4)
                }
                .buttonStyle(.plain)
                .accessibilityLabel("Upgrade to Pro Plan")
            }
        }

        struct MetricCardView: View {
            let title: String
            let value: String
            let trend: String
            let accentColor: Color

            var body: some View {
                VStack(alignment: .leading, spacing: 10) {
                    Text(title)
                        .font(.caption)
                        .foregroundColor(.secondary)
                    Text(value)
                        .font(.title2.weight(.bold))
                    Text(trend)
                        .font(.caption.weight(.semibold))
                        .foregroundColor(accentColor)
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding(14)
                .background(Color(.secondarySystemBackground))
                .clipShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
            }
        }

        #Preview {
            \(sanitizedName)View()
        }
        """

        let tokensCode = """
        //
        //  DesignTokens.swift
        //  Generated by DesignPilot SDK v1.0
        //

        import SwiftUI

        public enum DesignTokens {
            public enum Colors {
                public static let brandPrimary = Color(red: 0.08, green: 0.49, blue: 0.98)
                public static let brandSecondary = Color(red: 0.42, green: 0.22, blue: 0.89)
                public static let surfaceBackground = Color(red: 0.97, green: 0.98, blue: 0.99)
                public static let textPrimary = Color(red: 0.09, green: 0.11, blue: 0.15)
            }

            public enum Spacing {
                public static let xs: CGFloat = 4
                public static let sm: CGFloat = 8
                public static let md: CGFloat = 16
                public static let lg: CGFloat = 24
                public static let xl: CGFloat = 32
            }

            public enum Radii {
                public static let card: CGFloat = 12
                public static let button: CGFloat = 16
            }
        }
        """

        let files: [GeneratedFile] = [
            GeneratedFile(
                relativePath: "\(request.targetDirectory)/\(sanitizedName)View.swift",
                content: generatedSwiftUI,
                status: .created,
                framework: .swiftUI
            ),
            GeneratedFile(
                relativePath: "\(request.targetDirectory)/DesignTokens.swift",
                content: tokensCode,
                status: .created,
                framework: .designTokens
            )
        ]

        let extractedTokens = DesignTokens(
            colors: [
                ColorToken(name: "brandPrimary", red: 0.08, green: 0.49, blue: 0.98),
                ColorToken(name: "brandSecondary", red: 0.42, green: 0.22, blue: 0.89),
                ColorToken(name: "surfaceBackground", red: 0.97, green: 0.98, blue: 0.99),
                ColorToken(name: "textPrimary", red: 0.09, green: 0.11, blue: 0.15)
            ],
            typography: [
                TypographyToken(name: "HeaderLarge", fontFamily: "SF Pro Rounded", fontSize: 28, fontWeight: "Bold"),
                TypographyToken(name: "Headline", fontFamily: "SF Pro", fontSize: 17, fontWeight: "Semibold"),
                TypographyToken(name: "Caption", fontFamily: "SF Pro", fontSize: 12, fontWeight: "Regular")
            ],
            spacing: [
                SpacingToken(name: "xs", value: 4),
                SpacingToken(name: "sm", value: 8),
                SpacingToken(name: "md", value: 16),
                SpacingToken(name: "lg", value: 24)
            ],
            radii: [
                CornerRadiusToken(name: "card", value: 12),
                CornerRadiusToken(name: "button", value: 16)
            ],
            shadows: [
                ShadowToken(name: "cardShadow", colorHex: "#000000", colorAlpha: 0.08, radius: 8, x: 0, y: 4)
            ]
        )

        let visualDiff = VisualDiffReport(
            similarityScore: 0.984,
            acceptanceThreshold: request.visualAcceptanceThreshold,
            iterationCount: 2,
            testedDevices: ["iPhone 16 Pro", "iPad Air (11-inch)"],
            discrepancies: [
                VisualDiscrepancy(
                    type: .spacing,
                    elementName: "MetricCardView",
                    expected: "16pt inter-card spacing",
                    actual: "14pt inter-card spacing",
                    suggestedFix: "Adjust HStack spacing from 14 to 16",
                    severity: .low
                ),
                VisualDiscrepancy(
                    type: .typography,
                    elementName: "HeaderSection.Title",
                    expected: "SF Pro Rounded Bold 28pt",
                    actual: "System Rounded Bold 28pt",
                    suggestedFix: "Matches system fallback perfectly",
                    severity: .low
                )
            ]
        )

        return GenerationResult(
            figmaURL: request.figmaURL,
            generatedFiles: files,
            tokens: extractedTokens,
            visualDiff: visualDiff,
            screenName: sanitizedName
        )
    }

    public func integrate(request: IntegrationRequest) async throws -> IntegrationSummary {
        try await Task.sleep(nanoseconds: 600_000_000)
        let backupId = "backup_\(Int(Date().timeIntervalSince1970))"
        return IntegrationSummary(
            backupId: backupId,
            backupPath: ".designpilot/backups/\(backupId)",
            addedFiles: request.selectedFiles,
            modifiedFiles: [],
            preservedFiles: ["ContentView.swift", "AppDelegate.swift"],
            targetDirectory: request.targetDirectory
        )
    }

    public func rollback(backupId: String) async throws -> Bool {
        try await Task.sleep(nanoseconds: 400_000_000)
        return true
    }
}
